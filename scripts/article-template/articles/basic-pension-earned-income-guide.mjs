  //   상단: 근로소득 합계에서 공제를 한 번만 빼고 0 아래는 자른다. 하단: 일하는 사람마다 공제를 빼고 음수를 다른 소득·재산 환산액까지 상계한다
  //   (재산기준편 위젯과 같은 가정: 남는 공제는 모든 항과 상계할 수 있다고 본 값이 하단).
