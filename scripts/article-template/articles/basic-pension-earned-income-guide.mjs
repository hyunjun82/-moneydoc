  const maxS = derive(DED + Math.floor((TH_S * 10) / 7));
  const maxC = derive(DED + Math.floor((TH_C * 10) / 7));
  if (!(bp('single', earn(maxS)).isEligible && !bp('single', earn(maxS + 1)).isEligible)) throw new Error('단독 월급 상한이 엔진과 어긋난다');
  if (!(bp('couple', earn(maxC)).isEligible && !bp('couple', earn(maxC + 1)).isEligible)) throw new Error('부부 월급 상한이 엔진과 어긋난다');
