    const lo = Math.max(0, ws.reduce((x, w) => x + ((w - DED) * 7) / 10, 0) + other + prop);
    const assume = [];
    if (ws.length >= 2) assume.push('two');
    if (ws.some((w) => w < DED) && other + prop > 0) assume.push('under');
    return { lo, up, assume };
