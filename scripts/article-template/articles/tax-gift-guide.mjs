  const GA = withSur(A, SUR), GM = withSur(M, SUR);        // 성인·미성년 손주가 조부모에게서 1억원

  // ── s1: 성인이 두 사람에게서 3,000만원씩 받을 때 (묶음) ──────────────────
  const SAME = 3e7;
  const PAIR = derive(SAME * 2);
  const BOTH = gift(PAIR, 'lineal_adult');                  // 아버지 + 어머니: 한 사람으로 합산
  const LATER = gift(BOTH.taxableBase, 'other');            // 한도를 채우고 남은 과세표준에 붙는 세금 (공제 0원 관계로 과세표준을 그대로 넣는다)
  must(LATER.payableTax === BOTH.payableTax, '남은 과세표준 세금이 합산 세금과 다르다');
  const GP_LATER = withSur(LATER, SUR);                     // 할아버지 돈을 나중에 받으면 그 과세표준에 할증
  const STRANGER = gift(SAME, 'other');
  must(gift(SAME, 'spouse').payableTax === 0 && gift(SAME, 'lineal_adult').payableTax === 0, '한도 안 3,000만원에 세금이 나온다');
  const EDGE = gift(derive(AD + C.MIN_TAXABLE_BASE), 'lineal_adult');   // 한도보다 50만원 많이 받은 성인 자녀
  must(gift(derive(AD + C.MIN_TAXABLE_BASE - 1e4), 'lineal_adult').payableTax === 0 && EDGE.payableTax > 0, '과세최저한 경계가 엔진과 다르다');

  // ── s2: 같은 1억원, 다섯 가지 경우 ───────────────────────────────────────
  const TOP10 = derive(BR[0].upperBound + AD);              // 성인 자녀가 면제한도만 뺄 때 10% 구간이 끝나는 받은 금액
  const USED = gift(TOP10, 'lineal_adult');                 // 10년 안에 같은 부모에게서 한도만큼 받은 뒤 1억원: 합산 1억 5,000만원
  must(gift(AD, 'lineal_adult').tax === 0, '한도만큼 받은 첫 증여에 산출세액이 있다');
  const MARRY_FREE = gift(derive(HUND - MARRY), 'lineal_adult');
  must(MARRY_FREE.payableTax === 0, '혼인·출산 공제 뒤 세금이 0원이 아니다');
  const P = (a) => gift(a, 'lineal_adult').payableTax;
  const STEP = derive(BR[0].upperBound / 10);               // 1,000만원씩 더 받을 때
  const STEP10 = derive(P(HUND + STEP) - P(HUND));
  const STEP20 = derive(P(2e8 + STEP) - P(2e8));

  // ── s3: 3억원을 받는 세 가지 방법 (10년 합산과 납부세액공제) ────────────
  const HALF = TOP10;
  const WHOLE = derive(HALF * 2);
  const G15 = gift(HALF, 'lineal_adult'), G30 = gift(WHOLE, 'lineal_adult');
  const SECOND_TAX = derive(G30.tax - G15.tax);             // 합산 산출세액 − 앞 증여의 산출세액 (법 제58조제1항)
  const CREDIT_CAP = derive(Math.floor(G30.tax * G15.taxableBase / G30.taxableBase));   // 공제 한도 (법 제58조제2항)
  must(G15.tax <= CREDIT_CAP, '납부세액공제 한도에 걸린다');
  const SECOND = derive(SECOND_TAX - Math.floor(SECOND_TAX * C.FILING_CREDIT_RATE));
  const TWICE = derive(G15.payableTax * 2);
  must(G15.payableTax + SECOND === G30.payableTax, '10년 안에 나눠 받은 합계가 한 번에 받은 세금과 다르다');

  // ── s4: 혼인·출산 공제 (받은 금액에서 1억원을 먼저 뺀다) ────────────────
  const G30_MARRY = gift(derive(WHOLE - MARRY), 'lineal_adult');   // 3억원에서 혼인·출산 공제를 먼저 뺀 2억원
  const MARRY_TOP = derive(AD + MARRY);                     // 면제한도 + 혼인·출산 공제

  // ── s6: 신고 시기별 (무신고가산세와 기한 후 신고 감면) ──────────────────
  const NOFILE = derive(Math.round(A.tax * NOFILE_R)), NOFILE_BAD = derive(Math.round(A.tax * NOFILE_BAD_R));
  const LATE = [['기한 뒤 1개월 이내 (7월 31일까지)', '절반 감면'], ['1개월 초과 3개월 이내 (9월 30일까지)', `${pct(CUTS[1])} 감면`], ['3개월 초과 6개월 이내 (12월 31일까지)', `${pct(CUTS[2])} 감면`]]
    .map(([when, how], i) => { const pen = derive(Math.round(NOFILE * (1 - CUTS[i]))); return { when, how, pen, total: derive(A.tax + pen) }; });

