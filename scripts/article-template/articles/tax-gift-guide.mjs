  const REL = [['lineal_adult', '부모가 성인 자녀에게'], ['lineal_minor', '부모가 미성년 자녀에게'], ['spouse', '배우자에게'], ['lineal_adult', '자녀가 부모에게'], ['sibling', '형제자매, 며느리·사위 같은 그 밖의 친족에게'], ['other', '친족이 아닌 사람에게']];

