      sub1: `성인 자녀 ${kw(AD)}원, 미성년 ${kw(MD)}원`,
      sub2: '넘는 금액에 10%부터 50%까지',
      foot: `상속세 및 증여세법 · ${VERIFIED} 검증`,
      card: { label: '성인 자녀에게 1억원', big: won(A.payableTax), unit: '원', l1: `미성년 자녀면 ${won(M.payableTax)}원`, l2: '기한 안에 신고했을 때' },
