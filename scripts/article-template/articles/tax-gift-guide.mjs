  const MARRY = amt(Q.marry, /별개로 (\S+?원)을/);                          // 혼인·출산 공제 1억원 (법 제53조의2)
  const SUR = rate(Q.sur, /산출세액에 100분의 (\d+)\(/);                    // 할증 30% (법 제57조제1항)
  const SUR_MINOR = rate(Q.sur, /초과하는 경우에는 100분의 (\d+)\)/);       // 미성년·20억원 초과 40%
