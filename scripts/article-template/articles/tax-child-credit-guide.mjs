  const TAX_LOW = derive(14000000 * 6 / 100);                 // 제55조 세율표 첫 구간
  // 근로소득세액공제(제59조①): 산출세액 130만원 이하면 그 55%. 한도(제59조②)는 총급여 1억2천만원 이하에서 50만원 이상이라 이 예에서는 걸리지 않는다
