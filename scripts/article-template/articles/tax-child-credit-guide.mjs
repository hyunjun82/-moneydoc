    const ok = []; for (let b = y - 30; b <= y; b++) if (counts(y, b)) ok.push(b);
    if (ok[ok.length - 1] - ok[0] !== ok.length - 1) throw new Error(`${y}년 대상 출생연도가 한 구간이 아니다`);
