  const cut = (a, b) => derive(reg(a + b) - reg(a) - reg(b));
  for (let n = 2; n <= 10; n++) for (let a = 1; a < n; a++) if (reg(a) + reg(n - a) >= reg(n)) throw new Error('나누면 줄어든다는 문장이 틀렸다');
