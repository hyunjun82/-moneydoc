  const rawLocal20 = derive(T20.dailyTax * C.LOCAL_TAX_RATE);
  if (T20.dailyLocalTax !== Math.floor(rawLocal20 / 10) * 10) throw new Error('tax-daily-wage-guide: 끝수 처리가 엔진과 다르다');

  // 세금 0원 경계. 계산한 소득세(공제 뒤 금액 × 2.7%)가 1,000원 미만인 마지막 일급
  const ZERO_MAX = C.EXEMPT_AMOUNT + Math.ceil(1000 / C.EFFECTIVE_TAX_RATE) - 1;
  const B0 = dw(ZERO_MAX), B1 = dw(ZERO_MAX + 1);
  if (B0.dailyTax !== 0 || B1.dailyTax === 0) throw new Error('tax-daily-wage-guide: 0원 경계가 엔진과 다르다');
  const drop = derive(ZERO_MAX - B1.netDailyWage);                               // 1원 올랐을 때 줄어드는 실수령
  // 실수령이 경계 일급보다 적은 구간의 끝. 엔진을 187,038~700,000원 전부 돌려 확인했다 (2026-11-18):
  // 187,038~188,166원만 적고(끊김 없음) 188,167원에서 같아지며 그 위로는 전부 많다.
  const REV_END = 188166;
  if (!(dw(REV_END).netDailyWage < ZERO_MAX && dw(REV_END + 1).netDailyWage === ZERO_MAX && dw(REV_END + 2).netDailyWage > ZERO_MAX)) throw new Error('tax-daily-wage-guide: 실수령 역전 구간이 엔진과 다르다');
  const rawTax = (w) => derive(+(Math.max(0, w - C.EXEMPT_AMOUNT) * C.EFFECTIVE_TAX_RATE).toFixed(3));
  const num3 = (v) => (Number.isInteger(v) ? won(v) : v.toLocaleString('ko-KR', { minimumFractionDigits: 3, maximumFractionDigits: 3 }));
  const EDGE = [150000, 180000, ZERO_MAX, ZERO_MAX + 1, REV_END + 1];
  const LUMP_W = 180000, LUMP_N = 20;                                            // 몰아 받는 예시: 하루 810원, 20일 합계 16,200원
  const lumpSum = derive(rawTax(LUMP_W) * LUMP_N);

  // 하루 공제는 그날 일급에서만
  const LOW = 100000;
  if (dw(LOW).totalDailyDeduct !== 0) throw new Error('tax-daily-wage-guide: 일급 10만원 세금이 0이 아니다');
  const unused = derive(C.EXEMPT_AMOUNT - LOW);
  const BIG = dw(450000);
  if (dw(C.EXEMPT_AMOUNT, 3).totalDailyDeduct !== 0) throw new Error('tax-daily-wage-guide: 일급 15만원 세금이 0이 아니다');

  // 3.3% 하루 비교
  const CMP = [150000, 250000, 350000, 450000].map((w) => { const d = dw(w), f = fr(w); return { w, d, f, gap: derive(f.totalTax - d.totalDailyDeduct) }; });
  const SMALL = fr(30000);                                                       // 3만원 × 3% = 900원. 계속·반복 인적 용역은 소액 부징수 예외

  // 기한 예시: 2027년 3월 지급분. 토·일요일이면 다음 날로 (국세기본법 제5조①). 4월 12일·30일은 공휴일이 아니다
  const KDAY = ['일', '월', '화', '수', '목', '금', '토'];
