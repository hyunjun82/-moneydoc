  const CMPDAYS = Array.from({ length: 31 }, (_, i) => i + 1).map((n) => ({ n, d: R.totalDailyDeduct * n, s: salMonthTax(n) }));
  const CROSS = CMPDAYS.find((x) => x.s > x.d).n;                                // 월급 방식이 더 떼기 시작하는 날수
  if (!CMPDAYS.every((x) => (x.n < CROSS ? x.s < x.d : x.s > x.d))) throw new Error('tax-daily-wage-guide: 일용·월급 방식 비교가 한 번만 뒤집히지 않는다');
  if (!(CROSS <= 20 && salTax > sum20)) throw new Error('tax-daily-wage-guide: 한 달 500만원 예시에서 월급 방식이 더 떼지 않는다 (본문 문장을 고쳐야 한다)');
  const LOWDAY = CMPDAYS[CROSS - 2];                                             // 뒤집히기 직전 날수의 두 금액
  derive(LOWDAY.d); derive(LOWDAY.s);

  // 끝수 예시: 일급 20만원 (계산기 기본값). 지방소득세 135원에서 10원 미만을 버려 130원
