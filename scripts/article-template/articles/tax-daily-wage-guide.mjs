  const md = (t) => `${t.getUTCMonth() + 1}월 ${t.getUTCDate()}일(${KDAY[t.getUTCDay()]})`;
  if (new Date(Date.UTC(YEAR, 3, 10)).getUTCDay() !== 6) throw new Error('tax-daily-wage-guide: 기한 예시의 4월 10일이 토요일이 아니다');
  const PAY_DUE = shift(4, 10), STMT_DUE = shift(4, 30);

